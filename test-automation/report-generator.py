#!/usr/bin/env python3
"""
Test Report Generator

Generates comprehensive HTML and Markdown reports from test results JSON.
"""

import json
import sys
from pathlib import Path
from datetime import datetime
from typing import Dict, List, Any


class ReportGenerator:
    """Generate comprehensive test reports"""

    def __init__(self, results_file: str):
        self.results_file = Path(results_file)
        self.results: Dict[str, Any] = {}
        self.load_results()

    def load_results(self):
        """Load test results from JSON file"""
        if not self.results_file.exists():
            raise FileNotFoundError(f"Results file not found: {self.results_file}")

        with self.results_file.open('r') as f:
            self.results = json.load(f)

    def generate_html_report(self, output_path: str):
        """Generate comprehensive HTML report"""
        html = self._build_html()

        output = Path(output_path)
        output.parent.mkdir(parents=True, exist_ok=True)

        with output.open('w') as f:
            f.write(html)

        print(f"✅ HTML report generated: {output_path}")

    def generate_markdown_report(self, output_path: str):
        """Generate markdown report"""
        md = self._build_markdown()

        output = Path(output_path)
        output.parent.mkdir(parents=True, exist_ok=True)

        with output.open('w') as f:
            f.write(md)

        print(f"✅ Markdown report generated: {output_path}")

    def _build_html(self) -> str:
        """Build complete HTML report"""
        summary = self.results.get('summary', {})
        tests = self.results.get('tests', [])
        timestamp = self.results.get('timestamp', '')
        test_run_id = self.results.get('test_run_id', '')

        # Calculate statistics
        stats = self._calculate_statistics(tests)

        html = f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>Claude Code Helper - Test Report</title>
    <style>
        {self._get_css()}
    </style>
</head>
<body>
    <div class="container">
        <header>
            <h1>🧪 Claude Code Helper - Test Report</h1>
            <p class="subtitle">Automated Test Execution Results</p>
            <div class="meta">
                <span>Run ID: {test_run_id}</span>
                <span>Timestamp: {timestamp}</span>
            </div>
        </header>

        {self._build_summary_section(summary, stats)}
        {self._build_statistics_section(stats)}
        {self._build_test_results_section(tests)}
        {self._build_recommendations_section(summary, stats)}

        <footer>
            <p>Generated by Claude Code Helper Test Automation Framework v1.0.0</p>
            <p>Report generated at: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}</p>
        </footer>
    </div>

    <script>
        {self._get_javascript()}
    </script>
</body>
</html>"""
        return html

    def _build_summary_section(self, summary: Dict, stats: Dict) -> str:
        """Build executive summary section"""
        total = summary.get('total', 0)
        passed = summary.get('passed', 0)
        failed = summary.get('failed', 0)
        skipped = summary.get('skipped', 0)
        pass_rate = summary.get('pass_rate', 0)

        # Determine overall status
        if pass_rate >= 95:
            status = "EXCELLENT"
            status_class = "success"
        elif pass_rate >= 80:
            status = "GOOD"
            status_class = "warning"
        else:
            status = "NEEDS ATTENTION"
            status_class = "danger"

        return f"""
        <section class="summary">
            <h2>📊 Executive Summary</h2>
            <div class="status-badge {status_class}">
                Overall Status: {status}
            </div>
            <div class="metrics-grid">
                <div class="metric-card">
                    <div class="metric-value">{total}</div>
                    <div class="metric-label">Total Tests</div>
                </div>
                <div class="metric-card success">
                    <div class="metric-value">{passed}</div>
                    <div class="metric-label">Passed</div>
                </div>
                <div class="metric-card danger">
                    <div class="metric-value">{failed}</div>
                    <div class="metric-label">Failed</div>
                </div>
                <div class="metric-card warning">
                    <div class="metric-value">{skipped}</div>
                    <div class="metric-label">Skipped</div>
                </div>
            </div>
            <div class="progress-bar">
                <div class="progress-fill success" style="width: {(passed/total)*100 if total > 0 else 0}%"></div>
                <div class="progress-fill danger" style="width: {(failed/total)*100 if total > 0 else 0}%"></div>
                <div class="progress-fill warning" style="width: {(skipped/total)*100 if total > 0 else 0}%"></div>
            </div>
            <div class="pass-rate">
                <h3>Pass Rate: {pass_rate}%</h3>
            </div>
        </section>"""

