def main():
    """Main entry point"""
    if len(sys.argv) < 2:
        print("Usage: python report-generator.py <results.json> [--html output.html] [--md output.md]")
        sys.exit(1)

    results_file = sys.argv[1]
    html_output = None
    md_output = None

    # Parse arguments
    i = 2
    while i < len(sys.argv):
        if sys.argv[i] == '--html' and i + 1 < len(sys.argv):
            html_output = sys.argv[i + 1]
            i += 2
        elif sys.argv[i] == '--md' and i + 1 < len(sys.argv):
            md_output = sys.argv[i + 1]
            i += 2
        else:
            i += 1

    # Default outputs if not specified
    if not html_output and not md_output:
        html_output = results_file.replace('.json', '.html')
        md_output = results_file.replace('.json', '.md')

    try:
        generator = ReportGenerator(results_file)

        if html_output:
            generator.generate_html_report(html_output)

        if md_output:
            generator.generate_markdown_report(md_output)

        print("\n✅ Report generation complete!")

    except Exception as e:
        print(f"❌ Error generating reports: {e}")
        import traceback
        traceback.print_exc()
        sys.exit(1)


if __name__ == "__main__":
    main()
