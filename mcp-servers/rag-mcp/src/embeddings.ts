/**
 * Embedding Generation Layer
 *
 * Provides embedding generation using local models or OpenAI API
 */

/**
 * Interface for embedding generators
 */
export interface EmbeddingGenerator {
  /**
   * Generate embeddings for a text string
   * @param text Text to generate embeddings for
   * @returns Array of numbers representing the embedding
   */
  generate(text: string): Promise<number[]>;

  /**
   * Generate embeddings for multiple texts (batch)
   * @param texts Array of texts to generate embeddings for
   * @returns Array of embedding arrays
   */
  generateBatch(texts: string[]): Promise<number[][]>;

  /**
   * Get the dimension of embeddings generated by this generator
   */
  getDimension(): number;

  /**
   * Get the name/identifier of the model being used
   */
  getModelName(): string;
}

/**
 * Local embedding generator using Transformers.js
 * Runs entirely in Node.js without external API calls
 * Uses sentence-transformers/all-MiniLM-L6-v2 (384 dimensions)
 */
export class LocalEmbeddingGenerator implements EmbeddingGenerator {
  private pipeline: any = null;
  private modelName = "Xenova/all-MiniLM-L6-v2";
  private dimension = 384;

  async initialize(): Promise<void> {
    if (this.pipeline) return;

    const { pipeline } = await import("@xenova/transformers");
    console.error(`🔧 Loading local embedding model: ${this.modelName}`);
    this.pipeline = await pipeline("feature-extraction", this.modelName);
    console.error(`✅ Local embedding model loaded (${this.dimension} dimensions)`);
  }

  async generate(text: string): Promise<number[]> {
    await this.initialize();

    const output = await this.pipeline(text, {
      pooling: "mean",
      normalize: true,
    });

    // Convert to regular array
    return Array.from(output.data);
  }

  async generateBatch(texts: string[]): Promise<number[][]> {
    await this.initialize();

    const results: number[][] = [];
    for (const text of texts) {
      const embedding = await this.generate(text);
      results.push(embedding);
    }

    return results;
  }

  getDimension(): number {
    return this.dimension;
  }

  getModelName(): string {
    return this.modelName;
  }
}

/**
 * OpenAI embedding generator
 * Requires OPENAI_API_KEY environment variable
 * Uses text-embedding-3-small (1536 dimensions)
 */
export class OpenAIEmbeddingGenerator implements EmbeddingGenerator {
  private client: any = null;
  private modelName = "text-embedding-3-small";
  private dimension = 1536;

  async initialize(): Promise<void> {
    if (this.client) return;

    const { default: OpenAI } = await import("openai");
    const apiKey = process.env.OPENAI_API_KEY;

    if (!apiKey) {
      throw new Error(
        "OPENAI_API_KEY environment variable is required for OpenAI embeddings"
      );
    }

    this.client = new OpenAI({ apiKey });
    console.error(`✅ OpenAI embedding client initialized (${this.dimension} dimensions)`);
  }

  async generate(text: string): Promise<number[]> {
    await this.initialize();

    const response = await this.client.embeddings.create({
      model: this.modelName,
      input: text,
    });

    return response.data[0].embedding;
  }

  async generateBatch(texts: string[]): Promise<number[][]> {
    await this.initialize();

    const response = await this.client.embeddings.create({
      model: this.modelName,
      input: texts,
    });

    return response.data.map((item: any) => item.embedding);
  }

  getDimension(): number {
    return this.dimension;
  }

  getModelName(): string {
    return this.modelName;
  }
}

/**
 * Factory function to create embedding generator based on configuration
 */
export function createEmbeddingGenerator(
  type: "local" | "openai" = "local"
): EmbeddingGenerator {
  switch (type) {
    case "local":
      return new LocalEmbeddingGenerator();
    case "openai":
      return new OpenAIEmbeddingGenerator();
    default:
      throw new Error(`Unknown embedding generator type: ${type}`);
  }
}
